// Firestore emulator only. Never touches real customers or mints a real token.
const assert=require('node:assert/strict');
const admin=require('firebase-admin');
const {createStaffAccess}=require('./staff_access');
(async()=>{
 if(!process.env.FIRESTORE_EMULATOR_HOST)throw Error('Emulator required');
 const app=admin.initializeApp({projectId:'demo-pokpok-admin'},'staff-integration');
 const db=app.firestore();
 let clock=new Date('2026-09-26T08:00:00Z'),claims;
 const api=createStaffAccess({db,auth:{createCustomToken:async(uid,c)=>{claims={uid,token:c};return 'test-token';}},FieldValue:admin.firestore.FieldValue,Timestamp:admin.firestore.Timestamp,now:()=>clock});
 const owner={auth:{uid:'staff-test-owner',token:{}},data:{}};
 const shop=db.doc('shops/staff-test-owner');
 await shop.set({name:'Test shop',tier:'full',shopType:'retail',subscriptionStatus:'trial',trialEndsAt:admin.firestore.Timestamp.fromDate(new Date('2027-01-01'))});
 const created=await api.manage({...owner,data:{name:'Cashier',pin:'123456'}});
 const ref=shop.collection('staff').doc(created.id);
 assert.equal((await ref.get()).data().pin,undefined);
 for(let n=0;n<5;n++)await assert.rejects(api.switchSession({...owner,data:{staffId:created.id,pin:'000000'}}));
 await assert.rejects(api.switchSession({...owner,data:{staffId:created.id,pin:'123456'}}),e=>e.code==='resource-exhausted');
 clock=new Date(+clock+6*60000);
 await api.switchSession({...owner,data:{staffId:created.id,pin:'123456'}});
 const employee={auth:claims,data:{}};
 assert.equal(claims.token.staffRole,'cashier');assert.equal(claims.token.staffShopId,'staff-test-owner');
 await assert.rejects(api.manage({...employee,data:{name:'Fake owner',pin:'1234',role:'owner'}}),e=>e.code==='permission-denied');
 await shop.collection('products').doc('rice').set({name:'Rice',price:50,costPrice:20,stock:10});
 await shop.collection('settings').doc('shop').set({name:'Shop',promptpayId:'1234567890',lineUserId:'secret'});
 const workspace=await api.workspace(employee);
 assert.equal(workspace.products[0].costPrice,undefined);assert.equal(workspace.settings.lineUserId,undefined);
 const request={...employee,data:{requestId:'staff-test-sale-123',items:[{productId:'rice',quantity:2,optionIds:[]}],paid:100,expectedTotal:100,paymentMethod:'cash'}};
 const sale=await api.checkout(request);
 assert.equal(sale.receiptProfile.name,'Shop');
 assert.equal(sale.receiptProfile.vatEnabled,false);
 await shop.collection('settings').doc('shop').update({name:'Changed',receiptVatEnabled:true,receiptVatRate:7,taxId:'9100192800912',address:'Address'});
 assert.deepEqual((await api.checkout(request)).receiptProfile,sale.receiptProfile);
 assert.equal(sale.total,100);assert.equal(sale.items[0].costPrice,undefined);assert.match(sale.receiptNo,/^S-690926-/);
 assert.equal((await api.checkout(request)).id,sale.id);
 assert.equal((await shop.collection('products').doc('rice').get()).data().stock,8);
 assert.equal((await shop.collection('sales').doc(sale.id).get()).data().items[0].costPrice,20);
 await assert.rejects(api.checkout({...request,data:{...request.data,expectedTotal:1}}),e=>e.code==='already-exists');
 await assert.rejects(api.checkout({...request,data:{...request.data,discount:10}}),e=>e.code==='permission-denied');
 await assert.rejects(api.checkout({...request,data:{...request.data,requestId:'new-bad-price-123',expectedTotal:1}}),e=>e.code==='failed-precondition');
 assert.equal((await shop.collection('products').doc('rice').get()).data().stock,8);
 await api.manage({...owner,data:{id:created.id,name:'Cashier',pin:'654321'}});
 await assert.rejects(api.workspace(employee),e=>e.code==='permission-denied');
 await assert.rejects(api.checkout(request),e=>e.code==='permission-denied');
 await api.switchSession({...owner,data:{staffId:created.id,pin:'654321'}});
 await api.manage({...owner,data:{id:created.id,name:'Cashier',active:false}});
 await assert.rejects(api.workspace({auth:claims,data:{}}),e=>e.code==='permission-denied');
 for(const fn of Object.values(api))await assert.rejects(fn({data:{}}),e=>e.code==='unauthenticated');
 console.log('Staff integration: hashed PIN, lockout, custom claims, sanitized workspace, checkout replay/price/stock, PIN revocation and disabled staff passed.');
 await app.delete();
})().catch(e=>{console.error(e);process.exitCode=1;});
