const assert=require('node:assert/strict');
const admin=require('firebase-admin');
const {createOfflineSales}=require('./offline_sales');
(async()=>{
 if(!process.env.FIRESTORE_EMULATOR_HOST)throw Error('Emulator required');
 const app=admin.initializeApp({projectId:'demo-pokpok-admin'},'offline-integration'),db=app.firestore();
 let clock=new Date('2026-09-26T08:00:00Z');
 const api=createOfflineSales({db,Timestamp:admin.firestore.Timestamp,FieldValue:admin.firestore.FieldValue,now:()=>clock});
 const shop=db.doc('shops/offline-test-owner'),owner={auth:{uid:shop.id,token:{}},data:{}};
 await shop.set({name:'Offline shop',tier:'full',subscriptionStatus:'trial',trialEndsAt:admin.firestore.Timestamp.fromDate(new Date('2027-01-01'))});
 await shop.collection('products').doc('rice').set({name:'Rice',price:50,costPrice:20,stock:3});
 const permit=await api.prepare(owner);
 assert.equal(permit.products[0].costPrice,undefined);
 assert.equal(+new Date(permit.expiresAt)-+clock,12*3600000);
 const data={id:'offline-test-bill-0001',permitId:permit.id,secret:permit.secret,createdAt:clock.toISOString(),items:[{productId:'rice',quantity:2,optionIds:[]}],total:100,paid:120,discount:0,paymentMethod:'cash'};
 await assert.rejects(api.sync({data}),e=>e.code==='unauthenticated');
 await assert.rejects(api.sync({...owner,data:{...data,secret:'0'.repeat(64)}}),e=>e.code==='permission-denied');
 await assert.rejects(api.sync({...owner,data:{...data,total:1}}),e=>e.code==='invalid-argument');
 await assert.rejects(api.sync({...owner,data:{...data,paymentMethod:'qr'}}),e=>e.code==='invalid-argument');
 // Another till sold stock and the owner edited price during this outage.
 await shop.collection('products').doc('rice').update({price:80,stock:1});
 const results=await Promise.all([api.sync({...owner,data}),api.sync({...owner,data})]);
 assert.equal(results[0].receiptNo,results[1].receiptNo);
 assert.equal((await shop.collection('products').doc('rice').get()).data().stock,-1);
 const saved=(await shop.collection('sales').doc(data.id).get()).data();
 assert.equal(saved.total,100);assert.equal(saved.change,20);assert.equal(saved.needsReview,true);
 assert(saved.offlineReview.some(v=>v.includes('ราคา')));assert(saved.offlineReview.some(v=>v.includes('สต็อก')));
 await assert.rejects(api.sync({...owner,data:{...data,paid:130}}),e=>e.code==='already-exists');
 await assert.rejects(api.sync({...owner,data:{...data,id:'offline-after-expiry',createdAt:new Date(+clock+13*3600000).toISOString()}}),e=>e.code==='failed-precondition');
 await shop.collection('staff').doc('cashier').set({name:'Cashier',active:true,sessionVersion:1});
 const employee={auth:{uid:'staff_offline_test',token:{staffRole:'cashier',staffShopId:shop.id,staffId:'cashier',staffVersion:1}},data:{}};
 const staffPermit=await api.prepare(employee);
 await shop.collection('staff').doc('cashier').update({active:false,sessionVersion:2});
 await assert.rejects(api.prepare(employee),e=>e.code==='permission-denied');
 await shop.collection('products').doc('rice').delete();
 clock=new Date(+clock+24*3600000);
 const late=await api.sync({...owner,data:{...data,id:'offline-staff-late-sale',permitId:staffPermit.id,secret:staffPermit.secret,total:160,paid:160}});
 assert(late.review.some(v=>v.includes('สิทธิ์พนักงาน')));assert(late.review.some(v=>v.includes('สินค้าถูกลบ')));
 assert(late.review.some(v=>v.includes('หมดอายุ')));
 await assert.rejects(api.sync({auth:{uid:'unrelated',token:{}},data}),e=>e.code==='permission-denied');
 console.log('Offline integration passed: immutable pricing, concurrent idempotency, stock conflicts, late/revoked staff recovery, deleted products, forged totals/secrets and expiry.');
 await app.delete();
})().catch(e=>{console.error(e);process.exitCode=1;});
